import {createClient} from "https://esm.sh/@supabase/supabase-js@2";
const cors={"Access-Control-Allow-Origin":"*","Access-Control-Allow-Headers":"authorization, apikey, content-type","Access-Control-Allow-Methods":"POST, OPTIONS"};
Deno.serve(async req=>{
 if(req.method==="OPTIONS")return new Response("ok",{headers:cors});
 if(req.method!=="POST")return Response.json({error:"POST required"},{status:405,headers:cors});
 const url=Deno.env.get("SUPABASE_URL")!,anon=Deno.env.get("SUPABASE_ANON_KEY")!,service=Deno.env.get("SUPABASE_SERVICE_ROLE_KEY")!;
 const client=createClient(url,anon,{global:{headers:{Authorization:req.headers.get("Authorization")||""}}});
 const {data:{user},error:authError}=await client.auth.getUser();if(authError||!user)return Response.json({error:"Sign in required"},{status:401,headers:cors});
 const {sessionId,giveUp=false}=await req.json();if(typeof sessionId!=="string"||typeof giveUp!=="boolean")return Response.json({error:"Invalid result"},{status:400,headers:cors});
 const db=createClient(url,service);
 const {data:session}=await db.from("normal_game_sessions").select("*").eq("id",sessionId).eq("user_id",user.id).is("finished_at",null).maybeSingle();
 if(!session)return Response.json({error:"Game session not found or already submitted"},{status:404,headers:cors});
 const elapsed=(Date.now()-new Date(session.started_at).getTime())/1000;
 if(elapsed<0||(!giveUp&&elapsed<120))return Response.json({error:"Timer has not ended"},{status:409,headers:cors});
 if(elapsed>180)return Response.json({error:"Game session expired"},{status:410,headers:cors});
 const {data:answer}=await db.from("arcade_team_answers").select("roster").eq("team_id",session.team_id).maybeSingle();
 const total=(answer?.roster||[]).length;
 const {count}=await db.from("normal_game_session_guesses").select("*",{count:"exact",head:true}).eq("session_id",sessionId);
 const score=count||0;
 const {error:insertError}=await db.from("normal_game_results").insert({user_id:user.id,team_id:session.team_id,score,total});
 if(insertError)return Response.json({error:"Could not save result"},{status:500,headers:cors});
 await db.from("normal_game_sessions").update({finished_at:new Date().toISOString()}).eq("id",sessionId);
 const {data:percentile}=await db.rpc("team_percentile",{p_team_id:session.team_id,p_score:score,p_total:total});
 const {data:distribution}=await db.rpc("team_score_distribution",{p_team_id:session.team_id});
 return Response.json({score,total,outscoredPercent:percentile,distribution:distribution||[]},{headers:cors});
});